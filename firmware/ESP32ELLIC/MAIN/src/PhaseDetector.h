#pragma once

// ============================================================
// PhaseDetector
// ============================================================
//
// Определяет фазовое положение механизма по абсолютному
// углу коленвала.
//
// Коленвал механически связан с осями колёс.
// Поэтому угол коленвала определяет фазу шага.
//
// PhaseDetector НЕ отвечает за:
//   - чтение энкодера;
//   - калибровку;
//   - тормоза;
//   - ODrive;
//   - управление движением;
//   - BLE.
//
// Он только интерпретирует уже полученный абсолютный угол
// вала.
// ============================================================

class PhaseDetector
{
public:

    // --------------------------------------------------------
    // TURN ZONE
    // --------------------------------------------------------

    // Проверяет, находится ли коленвал в положении,
    // при котором оси колёс находятся примерно на одной оси
    // и ELLIC может выполнять поворот.
    //
    // valRawAngle:
    //     абсолютный угол коленвала 0...360°.
    //
    // Зоны:
    //     350...360°
    //     0...10°
    //     170...190°
    //
    static bool inTurnZone(float valRawAngle);
};